esp_err_t lcd_text_init(void) 
{
    ESP_LOGI(TAG, "Configuring Backlight...");
    gpio_reset_pin(PIN_NUM_BK_LIGHT);
    gpio_set_direction(PIN_NUM_BK_LIGHT, GPIO_MODE_OUTPUT);
    gpio_set_level(PIN_NUM_BK_LIGHT, 1);

    ESP_LOGI(TAG, "Configuring SPI Bus...");
    spi_bus_config_t buscfg = {
        .sclk_io_num = PIN_NUM_SCLK,
        .mosi_io_num = PIN_NUM_MOSI,
        .miso_io_num = -1,
        .quadwp_io_num = -1,
        .quadhd_io_num = -1,
        .max_transfer_sz = LCD_H_RES * LCD_V_RES * sizeof(uint16_t),
    };
    ESP_ERROR_CHECK(spi_bus_initialize(SPI2_HOST, &buscfg, SPI_DMA_CH_AUTO));

    esp_lcd_panel_io_handle_t io_handle = NULL;
    esp_lcd_panel_io_spi_config_t io_config = {
        .dc_gpio_num = PIN_NUM_LCD_DC,
        .cs_gpio_num = PIN_NUM_LCD_CS,
        .pclk_hz = 10 * 1000 * 1000, // 10MHz
        .lcd_cmd_bits = 8,
        .lcd_param_bits = 8,
        .spi_mode = 0,
        .trans_queue_depth = 10,
    };
    ESP_ERROR_CHECK(esp_lcd_new_panel_io_spi((esp_lcd_spi_bus_handle_t)SPI2_HOST, &io_config, &io_handle));

    esp_lcd_panel_dev_config_t panel_config = {
        .reset_gpio_num = -1, // Set to -1 temporarily to prevent PSRAM GPIO conflicts
        .rgb_endian = LCD_RGB_ENDIAN_BGR,
        .bits_per_pixel = 16,
    };
    ESP_ERROR_CHECK(esp_lcd_new_panel_st7789(io_handle, &panel_config, &panel_handle));

    vTaskDelay(pdMS_TO_TICKS(100));
    ESP_ERROR_CHECK(esp_lcd_panel_reset(panel_handle));
    vTaskDelay(pdMS_TO_TICKS(100));
    ESP_ERROR_CHECK(esp_lcd_panel_init(panel_handle));
    vTaskDelay(pdMS_TO_TICKS(100));

    //********************added by Trion on 2026/09/09********************
    // Change swap_xy and mirror flags to orient top-left properly
    ESP_ERROR_CHECK(esp_lcd_panel_swap_xy(panel_handle, false));

    // Try setting mirror_x = true and mirror_y = false to flip both axes correctly
    ESP_ERROR_CHECK(esp_lcd_panel_mirror(panel_handle, true, true));
    //********************added by Trion on 2026/09/09********************

    //ESP_ERROR_CHECK(esp_lcd_panel_invert_color(panel_handle, true));
    ESP_ERROR_CHECK(esp_lcd_panel_invert_color(panel_handle, false));

    ESP_ERROR_CHECK(esp_lcd_panel_disp_on_off(panel_handle, true));

    return ESP_OK;
}

void lcd_text_clear(uint16_t color) 
{
    uint16_t color_swapped = (color >> 8) | (color << 8);
    uint16_t *buffer = malloc(LCD_H_RES * 20 * sizeof(uint16_t));
    if (!buffer) return;

    for (int i = 0; i < LCD_H_RES * 20; i++) 
    {
        buffer[i] = color_swapped;
    }

    for (int y = 0; y < LCD_V_RES; y += 20) 
    {
        esp_lcd_panel_draw_bitmap(panel_handle, 0, y, LCD_H_RES, y + 20, buffer);
    }

    free(buffer);
}


static void draw_char(uint16_t x, uint16_t y, char c, uint16_t fg_color, uint16_t bg_color) 
{
    if (c < 32 || c > 126) return;

    uint16_t fg_swapped = (fg_color >> 8) | (fg_color << 8);
    uint16_t bg_swapped = (bg_color >> 8) | (bg_color << 8);

    uint16_t char_buf[8 * 16];
    
    // Explicitly wipe entire buffer to background color first
    for (int i = 0; i < 128; i++) 
    {
        char_buf[i] = bg_swapped;
    }

    const uint8_t *glyph = font8x16[c - 32];

    for (int row = 0; row < 16; row++) 
    {
        uint8_t line = glyph[row];
        for (int col = 0; col < 8; col++) 
        {
            if (line & (0x80 >> col)) 
            {
                char_buf[row * 8 + col] = fg_swapped;
            }
        }
    }

    int nValToSubtrack=0;
    esp_lcd_panel_draw_bitmap(panel_handle, x, y, x + 8-nValToSubtrack, y + 16-nValToSubtrack, char_buf);
}

void lcd_text_print(uint16_t x, uint16_t y, const char *text, uint16_t fg_color, uint16_t bg_color) 
{
    if (!text || !*text) return;

    size_t len = strlen(text);
    uint16_t fg_swapped = (fg_color >> 8) | (fg_color << 8);
    uint16_t bg_swapped = (bg_color >> 8) | (bg_color << 8);

    // Allocate memory for the whole string line (8 * length wide, 16 high)
    uint16_t str_width = len * CHAR_WIDTH;
    uint16_t str_height = CHAR_HEIGHT;

    // Boundary check
    if (x + str_width > LCD_H_RES || y + str_height > LCD_V_RES) 
    {
        // Fall back to char-by-char if string exceeds bounds or line-wrapping needed
        uint16_t cur_x = x;
        uint16_t cur_y = y;
        while (*text) 
        {
            if (*text == '\n') 
            {
                cur_x = x;
                cur_y += CHAR_HEIGHT;
            } 
            else 
            {
                draw_char(cur_x, cur_y, *text, fg_color, bg_color);
                cur_x += CHAR_WIDTH;
            }
            text++;
        }
        return;
    }

    // Calculate total buffer length in pixels
    // added by Trion on 2026/09/09
    int nAddVal=1;  //make it 1 to add one more buffer space in case that it may draw extra one stain under the last character.
    uint32_t total_pixels = str_width * str_height + nAddVal;

    // Allocate buffer with heap_caps for SPI DMA capability and 4-byte alignment
    uint16_t *line_buf = heap_caps_malloc(total_pixels * sizeof(uint16_t), MALLOC_CAP_DMA | MALLOC_CAP_INTERNAL);
    if (!line_buf) return;

    // Fill completely with background color
    for (size_t i = 0; i < total_pixels; i++) 
    {
        line_buf[i] = bg_swapped;
    }
    // added by Trion on 2026/09/09


    // Render characters into single buffer
    for (size_t char_idx = 0; char_idx < len; char_idx++) 
    {
        char c = text[char_idx];
        if (c < 32 || c > 126) continue;

        const uint8_t *glyph = font8x16[c - 32];
        for (int row = 0; row < 16; row++) 
        {
            uint8_t line = glyph[row];
            for (int col = 0; col < 8; col++) 
            {
                if (line & (0x80 >> col)) 
                {
                    uint32_t buf_x = (char_idx * 8) + col;
                    uint32_t buf_y = row;
                    line_buf[buf_y * str_width + buf_x] = fg_swapped;
                }
            }
        }
    }

    int nValToSubtrack=0;
    // Send the entire string in ONE clean SPI transfer
    esp_lcd_panel_draw_bitmap(panel_handle, x, y, x + str_width-nValToSubtrack, y + str_height-nValToSubtrack, line_buf);

    free(line_buf);
}


uint16_t html_to_rgb565(const char *html_hex) 
{
    // Skip '#' if present
    if (html_hex[0] == '#') 
    {
        html_hex++;
    }

    // Parse the 24-bit hex string into an integer
    uint32_t rgb888 = (uint32_t)strtoul(html_hex, NULL, 16);

    // Extract individual 8-bit channels
    uint8_t r = (rgb888 >> 16) & 0xFF;
    uint8_t g = (rgb888 >> 8)  & 0xFF;
    uint8_t b = rgb888         & 0xFF;

    // Scale down and pack into RGB565 format
    // Red:   keep top 5 bits, shift left by 11
    // Green: keep top 6 bits, shift left by 5
    // Blue:  keep top 5 bits, shift left by 0
    uint16_t rgb565 = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3);

    return rgb565;
}

void lcd_text_print_ex(uint16_t x, uint16_t y, const char *text, uint16_t fg_color, uint16_t bg_color, 
    bool bClearScreen,uint16_t unClearScreenWaitTime,uint16_t unWaitTimeAfterPrint, lcd_text_alignment alignment)
{
    if (bClearScreen)
    {
        lcd_text_clear(bg_color);
        vTaskDelay(pdMS_TO_TICKS(unClearScreenWaitTime));
    }

    int nLen=strlen(text);

    switch (alignment)
    {
    case LCD_TEXT_ALIGN_ANY:
        {
            lcd_text_print(x,y,text,fg_color,bg_color);      
        }
        break;

    case LCD_TEXT_ALIGN_TOPLEFT:
        {
            lcd_text_print(0,0,text,fg_color,bg_color);        
        }
        break;

    case LCD_TEXT_ALIGN_TOPCENTER:
        {
            int nXPos=(LCD_H_RES-(CHAR_WIDTH*nLen))/2;
            lcd_text_print(nXPos,0,text,fg_color,bg_color);        
        }
        break;

    case LCD_TEXT_ALIGN_TOPRIGHT:
        {
            int nXPos=(LCD_H_RES-(CHAR_WIDTH*nLen));
            lcd_text_print(nXPos,0,text,fg_color,bg_color);        
        }
        break;

    case LCD_TEXT_ALIGN_MIDDLELEFT:
        {
            int nYPos=(LCD_V_RES-CHAR_HEIGHT)/2;
            lcd_text_print(0,nYPos,text,fg_color,bg_color);        
        }
        break;

    case LCD_TEXT_ALIGN_MIDDLECENTER:
        {
            int nYPos=(LCD_V_RES-CHAR_HEIGHT)/2;
            int nXPos=(LCD_H_RES-(CHAR_WIDTH*nLen))/2;

            lcd_text_print(nXPos,nYPos,text,fg_color,bg_color);        
        }
        break;

    case LCD_TEXT_ALIGN_MIDDLELRIGHT:
        {
            int nYPos=(LCD_V_RES-CHAR_HEIGHT)/2;
            int nXPos=(LCD_H_RES-(CHAR_WIDTH*nLen));
            lcd_text_print(nXPos,nYPos,text,fg_color,bg_color);        
        }
        break;

    case LCD_TEXT_ALIGN_BOTTOMLEFT:
        {
            int nYPos=(LCD_V_RES-CHAR_HEIGHT);
            lcd_text_print(0,nYPos,text,fg_color,bg_color);        
        }

    case LCD_TEXT_ALIGN_BOTTOMCENTER:
        {
            int nYPos=(LCD_V_RES-CHAR_HEIGHT);
            int nXPos=(LCD_H_RES-(CHAR_WIDTH*nLen))/2;
            lcd_text_print(nXPos,nYPos,text,fg_color,bg_color);        
        }
        break;

    case LCD_TEXT_ALIGN_BOTTOMRIGHT:
        {
            int nYPos=(LCD_V_RES-CHAR_HEIGHT);
            int nXPos=(LCD_H_RES-(CHAR_WIDTH*nLen));
            lcd_text_print(nXPos,nYPos,text,fg_color,bg_color);        
        }
        break;
    
    default:
        break;
    }

    vTaskDelay(pdMS_TO_TICKS(unWaitTimeAfterPrint));
}

