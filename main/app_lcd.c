void test_print_text_dma(esp_lcd_panel_handle_t panel_handle, const char *text, int x_start, int y_start) 
{
    int text_len = strlen(text);
    
    // Calculate size of the combined bitmap window
    int total_width = text_len * CHAR_WIDTH;
    int total_height = CHAR_HEIGHT;
    size_t buffer_size = total_width * total_height * sizeof(uint16_t);

    // 1. Allocate DMA-capable memory for the text block
    uint16_t *text_buffer = (uint16_t *)heap_caps_malloc(buffer_size, MALLOC_CAP_DMA);
    if (text_buffer == NULL) {
        printf("DMA buffer allocation failed!\n");
        return;
    }

    // 2. Render text characters into the 1D RGB565 buffer row-by-row
    for (int y = 0; y < CHAR_HEIGHT; y++) {
        for (int c = 0; c < text_len; c++) {
            char ch = text[c];
            uint8_t font_row = 0;

            // Simple boundary protection for our test font array mapping
            if (ch >= 'A' && ch <= 'z') {
                font_row = font_8x8[ch - 'A'][y];
            }

            // Map the 8 bits of this row to RGB565 pixels
            for (int x = 0; x < CHAR_WIDTH; x++) {
                // Check if the bit is set from left to right (MSB to LSB)
                bool is_pixel_on = (font_row & (0x80 >> x)) != 0;
                
                // Calculate position in the final continuous 1D buffer
                int buffer_index = (y * total_width) + (c * CHAR_WIDTH + x);
                
                text_buffer[buffer_index] = is_pixel_on ? TEXT_COLOR : BG_COLOR;
            }
        }
    }

    // 3. Push the fake text bitmap straight to the LCD panel
    int x_end = x_start + total_width;
    int y_end = y_start + total_height;
    
    esp_lcd_panel_draw_bitmap(panel_handle, x_start, y_start, x_end, y_end, text_buffer);

    // Reminder: In production, track 'text_buffer' in your color_trans_done callback 
    // to free() it once DMA transmission finishes.
}
