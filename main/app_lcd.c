static void draw_char_to_buffer(uint16_t *buf, int buf_width, int buf_height, int x, int y, char c, uint16_t fg_color, uint16_t bg_color) 
{
    // 1. Bounds check (horizontal & vertical safety)
    if (x < 0 || y < 0 || (x + FONT_WIDTH) > buf_width || (y + FONT_HEIGHT) > buf_height) {
        return;
    }

    // 2. ASCII Index Mapping
    // If your font_8x16 array starts at ' ' (ASCII 32), subtract 32. 
    // If it starts at index 0 (full 256 ASCII), remove "- ' '" below.
    unsigned char char_index = (unsigned char)c;
    if (char_index < ' ' || char_index > '~') {
        char_index = ' '; // Fallback for unprintable characters
    }
    int font_idx = char_index - ' '; 

    // 3. Pre-swap colors to Big-Endian format required by ESP32 LCD controllers
    uint16_t fg_swapped = __builtin_bswap16(fg_color);
    uint16_t bg_swapped = __builtin_bswap16(bg_color);

    // 4. Pixel drawing loop
    for (int row = 0; row < FONT_HEIGHT; row++) {
        uint8_t bits = font_8x16[font_idx][row];
        for (int col = 0; col < FONT_WIDTH; col++) {
            // Check bit shift direction (0x80 >> col vs 0x01 << col depending on your font table)
            uint16_t pixel_color = (bits & (0x80 >> col)) ? fg_swapped : bg_swapped;
            
            buf[(y + row) * buf_width + (x + col)] = pixel_color;
        }
    }
}

