    // Screen dimensions
    const int disp_w = LCD_H_RES; // 320
    const int disp_h = LCD_V_RES; // 240

    // Allocate frame buffer in PSRAM (or heap if PSRAM unavailable)
    size_t buf_size = disp_w * disp_h * sizeof(uint16_t);
    uint16_t *frame_buf = (uint16_t *)heap_caps_malloc(buf_size, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT);
